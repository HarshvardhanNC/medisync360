def get_citation(company_name: str, topic: str) -> SourceCitation:
    """Retrieve citation for a specific insurer and rule topic."""
    comp_citations = SOURCE_REGISTRY.get(company_name, {})
    if topic in comp_citations:
        return comp_citations[topic]
    # Fallback to general citation if topic missing
    return next(iter(comp_citations.values()), SourceCitation(
        insurer=company_name,
        product_name="Retail Health Policy",
        uin="UNVERIFIED",
        clause_number="General Conditions",
        document_name="Policy Schedule",
        page_number=1,
        official_url="",
        verification_status="UNVERIFIED",
    ))

